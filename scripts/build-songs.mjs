#!/usr/bin/env node
// Builds everything the site needs from the songbooks' ChordPro files (the
// single source of truth; the books are listed in scripts/songs/books.mjs). For
// each book, with Песни's paths as the example:
//   src/data/songs/NNN.json      lyrics, sections, chords and credits for <ChordSheet>
//   docs/NNN.md                  the song page (other books: docs-<id>/N.md, plus an index page)
//   src/data/sidebars/<id>.json  the book's sidebar
//   typ/generated/*.typ          Typst modules for typ/single.typ, typ/lyrics.typ, typ/all.typ
//   static/pdf/N-slug.pdf        printable lyrics
//   static/chords/N-slug_akord.pdf  printable chord sheet (songs with chords)
//   static/openlp/*.xml          OpenLyrics for OpenLP, plus pesni-openlp.zip with all songs
//   static/cho/NNN-slug.cho      the source, for the "Предложи корекция" editor on the page
//   static/{pdf,chords,}/N/      short links: /pdf/52, /chords/52 and /52 lead to the song's files and page
//
// Runs before `npm run build` / `npm start`. A song that does not parse, uses an
// unknown directive or an unknown chord stops the build. PDFs are re-rendered
// only when their Typst module or the templates changed.
//
//   node scripts/build-songs.mjs              # everything
//   node scripts/build-songs.mjs 23 218       # selected song numbers (in every book)
//   node scripts/build-songs.mjs --force-pdf  # re-render the PDFs even if up to date
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {SongError, hasChords, openLyrics, page, pageData, parseSong, redirectPage, typModule} from './songs/lib.mjs';
import {BOOKS, bookPaths} from './songs/books.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const STATIC = path.join(ROOT, 'static');
const TYP = path.join(ROOT, 'typ');
const STYLE = path.join(TYP, 'style.typ');

function writeIfChanged(file, text) {
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text) return false;
    fs.mkdirSync(path.dirname(file), {recursive: true});
    fs.writeFileSync(file, text);
    return true;
}

function hasCommand(cmd) {
    try {
        execFileSync(cmd, ['--version'], {stdio: 'ignore'});
        return true;
    } catch (e) {
        return false;
    }
}

function isStale(sources, target) {
    if (!fs.existsSync(target)) return true;
    const built = fs.statSync(target).mtimeMs;
    return sources.some((s) => fs.statSync(s).mtimeMs > built);
}

function renderPdf(template, modulePath, pdfPath, force) {
    const templatePath = path.join(TYP, template);
    if (!force && !isStale([modulePath, templatePath, STYLE], pdfPath)) return false;
    fs.mkdirSync(path.dirname(pdfPath), {recursive: true});
    execFileSync('typst', ['compile', '--root', ROOT, '--input',
        `song=${path.relative(TYP, modulePath).split(path.sep).join('/')}`, templatePath, pdfPath], {stdio: 'inherit'});
    return true;
}

// The song's chord PDF from the old site, archived in static/old_chords (matched by
// slug, or by number when only one file has it).
function originalChords(number, slug) {
    const dir = path.join(STATIC, 'old_chords');
    const pdfs = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /_akord\.pdf$/i.test(f)) : [];
    const exact = pdfs.find((f) => f.toLowerCase() === `${number}-${slug}_akord.pdf`);
    const byNumber = pdfs.filter((f) => f.startsWith(`${number}-`));
    const file = exact || (byNumber.length === 1 ? byNumber[0] : null);
    return file && `/old_chords/${file}`;
}

const mdText = (text) => text.replace(/[{}<>[\]*_`\\]/g, (c) => `\\${c}`);

// Index page of a book other than Песни: its songs and extra links, at the book's root URL.
function indexPage(book, songs, paths) {
    const listed = book.groupBy === 'letter' ? [...songs].sort(byTitle) : songs;
    const entries = [
        ...listed.map(({number, title}) => `- [${number}. ${mdText(title)}](${paths.pageUrl(number)})`),
        ...(book.links || []).map(({label, href}) => `- [${mdText(label)}](${href})`),
    ];
    return [
        '---',
        '# Generated by scripts/build-songs.mjs from scripts/songs/books.mjs.',
        'slug: /',
        `title: ${JSON.stringify(book.label)}`,
        'sidebar_label: Всички',
        'hide_table_of_contents: true',
        '---',
        '',
        `# ${mdText(book.label)}`,
        '',
        ...(book.intro ? [mdText(book.intro), ''] : []),
        ...entries,
        '',
    ].join('\n');
}

const collator = new Intl.Collator('bg', {sensitivity: 'base', numeric: true});
const byTitle = (a, b) => collator.compare(a.title.replace(/^[^\p{L}\d]+/u, ''), b.title.replace(/^[^\p{L}\d]+/u, ''));
const initial = (title) => (title.replace(/^[^\p{L}\d]+/u, '')[0] || '#').toLocaleUpperCase('bg');

// Песни keeps its sidebar of fixed ranges (and their old URLs; the first range moved
// from / to /1-50/ when the site got a home page). Other books list their songs, then the extra links.
const PESNI_SLUGS = {1: '/1-50/', 51: '/51-100/', 101: '/101-150/', 151: '/150-201/', 201: '/201-250/'};

function sidebar(book, songs, paths) {
    if (paths.main) {
        const ranges = [];
        for (let lo = 1; lo <= Math.max(...songs.map((s) => s.number)); lo += 50) {
            const hi = lo + 49;
            ranges.push({
                type: 'category',
                label: `Песни ${lo}-${hi}`,
                items: songs.filter((s) => s.number >= lo && s.number <= hi).map((s) => paths.docId(s.number)),
                link: {type: 'generated-index', slug: PESNI_SLUGS[lo] || `/${lo}-${hi}/`},
                collapsed: false,
            });
        }
        return {songs: ranges};
    }
    let items = songs.map((s) => paths.docId(s.number));
    if (book.groupBy === 'letter') {
        const letters = new Map();
        for (const song of [...songs].sort(byTitle)) {
            const letter = initial(song.title);
            if (!letters.has(letter)) letters.set(letter, []);
            letters.get(letter).push(paths.docId(song.number));
        }
        items = [...letters].map(([letter, ids]) => ({type: 'category', label: letter, items: ids, collapsed: true}));
    } else if (book.groupBy) {
        const groups = [];
        for (let lo = 1; lo <= Math.max(...songs.map((s) => s.number)); lo += book.groupBy) {
            const hi = lo + book.groupBy - 1;
            groups.push({
                type: 'category',
                label: `${lo}-${hi}`,
                items: songs.filter((s) => s.number >= lo && s.number <= hi).map((s) => paths.docId(s.number)),
                collapsed: true,
            });
        }
        items = groups;
    }
    return {
        songs: [
            'index',
            ...items,
            ...(book.links || []).map(({label, href}) => ({type: 'link', label, href})),
        ],
    };
}

function buildBook(book, {wanted, forcePdf, typst, errors}) {
    const paths = bookPaths(book);
    const songsDir = path.join(ROOT, book.songs);
    const docsDir = path.join(ROOT, book.docs);
    const files = fs.readdirSync(songsDir).filter((f) => /^\d{3}-.+\.cho$/.test(f)).sort();
    const modules = [];
    const songs = [];
    let rendered = 0;
    let changedXml = false;
    for (const file of files) {
        const number = parseInt(file, 10);
        const id = file.slice(0, 3);
        const slug = file.slice(4, -4);
        const sourcePath = `${book.songs}/${file}`;
        const source = fs.readFileSync(path.join(songsDir, file), 'utf8');
        let song;
        try {
            song = parseSong(source);
        } catch (e) {
            if (!(e instanceof SongError)) throw e;
            errors.push(`${sourcePath}: ${e.message}`);
            continue;
        }
        songs.push({number, title: song.title});
        const modulePath = path.join(ROOT, paths.typ, `${id}-${slug}.typ`);
        const style = path.relative(path.dirname(modulePath), STYLE).split(path.sep).join('/');
        writeIfChanged(modulePath, typModule(number, song, sourcePath, style));
        modules.push([id, path.basename(modulePath)]);
        if (wanted.size && !wanted.has(number)) continue;

        const dataId = paths.main ? id : `${book.id}-${id}`;
        writeIfChanged(path.join(STATIC, 'cho', paths.cho, file), source);
        writeIfChanged(path.join(ROOT, paths.data, `${id}.json`), JSON.stringify(pageData(number, song, dataId)) + '\n');
        changedXml = writeIfChanged(path.join(ROOT, paths.openlp, `${number}-${slug}.xml`),
            openLyrics(number, song, book.label)) || changedXml;

        const lyricsPdf = `${paths.pdf}/${number}-${slug}.pdf`;
        const chordsPdf = hasChords(song) ? `${paths.chords}/${number}-${slug}_akord.pdf` : null;
        if (typst) {
            rendered += renderPdf('lyrics.typ', modulePath, path.join(STATIC, lyricsPdf), forcePdf);
            if (chordsPdf) rendered += renderPdf('single.typ', modulePath, path.join(STATIC, chordsPdf), forcePdf);
        }
        const downloads = [`<DownloadsButton pdf="${lyricsPdf}" />`];
        if (chordsPdf) downloads.push(`<DownloadChordsButton pdf="${chordsPdf}"/>`);
        const original = paths.main && originalChords(number, slug);
        if (original) downloads.push(`<DownloadChordsButton pdf="${original}" label="Акорди (оригинал)"/>`);
        writeIfChanged(path.join(docsDir, `${paths.docId(number)}.md`), page(number, song, {
            source: sourcePath, data: paths.dataImport(id), suggest: `${paths.cho}${file}`, downloads,
        }));

        if (paths.main) {
            // Short links by number. Song pages already answer to /100../239/.
            writeIfChanged(path.join(STATIC, 'pdf', String(number), 'index.html'), redirectPage(lyricsPdf));
            if (chordsPdf) writeIfChanged(path.join(STATIC, 'chords', String(number), 'index.html'), redirectPage(chordsPdf));
            if (String(number) !== id) writeIfChanged(path.join(STATIC, String(number), 'index.html'), redirectPage(`/${id}/`));
        }
    }

    if (!paths.main) writeIfChanged(path.join(docsDir, 'index.md'), indexPage(book, songs, paths));
    writeIfChanged(path.join(ROOT, paths.sidebar), JSON.stringify(sidebar(book, songs, paths), null, 1) + '\n');
    if (paths.main) {
        writeIfChanged(path.join(ROOT, paths.typ, 'songs.typ'),
            '// Generated by scripts/build-songs.mjs: every song module, in order.\n' +
            modules.map(([id, f]) => `#import "${f}" as song${id}`).join('\n') +
            `\n\n#let songs = (\n${modules.map(([id]) => `  song${id},`).join('\n')}\n)\n`);
    }

    const zip = path.join(ROOT, paths.zip);
    const xmlDir = path.join(ROOT, paths.openlp);
    if ((changedXml || !fs.existsSync(zip)) && hasCommand('zip')) {
        fs.rmSync(zip, {force: true});
        execFileSync('zip', ['-q', '-X', '-j', zip, ...fs.readdirSync(xmlDir).filter((f) => f.endsWith('.xml')).sort()
            .map((f) => path.join(xmlDir, f))]);
    }
    return {count: files.length, rendered};
}

function main() {
    const args = process.argv.slice(2);
    const forcePdf = args.includes('--force-pdf');
    const wanted = new Set(args.filter((a) => /^\d+$/.test(a)).map(Number));
    const typst = hasCommand('typst');
    if (!typst) console.warn('warning: typst not found, PDFs are not rendered');

    const errors = [];
    const results = BOOKS.map((book) => [book, buildBook(book, {wanted, forcePdf, typst, errors})]);
    // The books with their song counts, for the home page (src/pages/index.js).
    writeIfChanged(path.join(ROOT, 'src', 'data', 'books.json'), JSON.stringify(results.map(([book, r]) => ({
        id: book.id, label: book.label, route: book.route, intro: book.intro || '', count: r.count,
    })), null, 1) + '\n');
    // Where each book's pages live, for the suggestion review page (static/api/suggestions.php).
    writeIfChanged(path.join(STATIC, 'cho', 'books.json'),
        JSON.stringify(Object.fromEntries(BOOKS.map((book) => [bookPaths(book).cho.replace(/\/$/, ''), book.route]))) + '\n');
    if (errors.length) {
        console.error(`\n${errors.length} song(s) could not be built:\n  ${errors.join('\n  ')}`);
        process.exit(1);
    }
    console.log(results.map(([book, r]) => `${book.label}: ${wanted.size || r.count} songs, rendered ${r.rendered} PDFs`).join('; '));
}

main();
